// Copies the compiled contract ABIs from Foundry's out/ folder into packages/core/src/abi.ts,
// so the TypeScript code always matches the Solidity. Run after `forge build`: npm run abis
import { readFileSync, writeFileSync } from "node:fs";

const out = new URL("../contracts/out/", import.meta.url);
const contracts = {
  checkoutCoreAbi: "CheckoutCore.sol/CheckoutCore.json",
  uniswapCheckoutAbi: "UniswapCheckout.sol/UniswapCheckout.json",
  demoTokenAbi: "DemoToken.sol/DemoToken.json",
};

let ts = "// GENERATED by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n\n";
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(new URL(file, out), "utf8"));
  ts += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(new URL("../packages/core/src/abi.ts", import.meta.url), ts);
console.log("wrote packages/core/src/abi.ts");
